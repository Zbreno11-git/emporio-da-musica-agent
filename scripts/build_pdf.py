"""Build the delivery PDF (D17) from docs/delivery/report.template.html. Offline: no API calls.

Every number in the report is filled here from the generated files, never typed in the template:
- cost: scripts/cost_model.py (the -s9 benchmark turns and evals/pricing.json);
- tests and mutations: the summary table of docs/qa/README.md (literal tool output);
- hosted QA: docs/qa/hosted-results.md (generated by scripts/qa_capture.py);
- red-team battery and store scenarios: evals/benchmark/*-s9sec.jsonl and *-s9.jsonl;
- revision and examples: examples/raw/*.json (captured by scripts/capture_examples.py).
An unresolved {{placeholder}} fails the build.

Writes docs/delivery/report.html (committed, readable on GitHub as source) and the PDF at the repository root
(git-ignored). Usage: .venv/bin/python scripts/build_pdf.py
"""

from __future__ import annotations

import glob
import json
import re
import sys
from datetime import datetime
from pathlib import Path
from zoneinfo import ZoneInfo

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app.config import Settings  # noqa: E402
from scripts import cost_model  # noqa: E402

DELIVERY = ROOT / "docs" / "delivery"
PDF_NAME = "Breno Zamponi - AI Engineer – Full-Stack para Aplicações com IA Generativa.pdf"
TYPE_LABELS = {"quote": "Price or payment quote", "catalog_search": "Catalog search", "order": "Order status",
               "policy": "Store rule (manual)", "handoff": "Hand-off to the team", "out_of_scope": "Out of scope"}


def jsonl(name: str) -> list[dict]:
    path = ROOT / "evals" / "benchmark" / f"{cost_model.BENCHMARK_DATE}-{name}.jsonl"
    return [json.loads(line) for line in path.read_text().splitlines() if line]


def values() -> dict[str, str]:
    pricing = json.loads((ROOT / "evals" / "pricing.json").read_text())
    data = cost_model.build(pricing, ROOT / "evals" / "benchmark")
    rate, usd, brl = pricing["fx"]["usd_brl"], cost_model.usd, cost_model.brl
    pinned, alt = cost_model.MODELS
    p, a = data["models"][pinned], data["models"][alt]
    v = {
        "pinned": pinned, "alt": alt,
        "mean": usd(p["stats"]["mean_usd"], 5), "median": usd(p["stats"]["median_usd"], 5),
        "max": usd(p["stats"]["max_usd"], 5), "calls": f"{p['stats']['mean_model_calls']:.2f}",
        "latency": f"{p['stats']['mean_seconds']:.2f} s",
        "alt_mean": usd(a["stats"]["mean_usd"], 5), "alt_median": usd(a["stats"]["median_usd"], 5),
        "alt_max": usd(a["stats"]["max_usd"], 5), "alt_calls": f"{a['stats']['mean_model_calls']:.2f}",
        "alt_latency": f"{a['stats']['mean_seconds']:.2f} s",
        "per_1000": usd(p["stats"]["mean_usd"] * 1000), "per_1000_brl": brl(p["stats"]["mean_usd"] * 1000, rate),
        "turns_measured": str(p["stats"]["turns"]), "turns_per_conv": str(cost_model.TURNS_PER_CONVERSATION),
        "fx": f"{rate}", "fx_date": pricing["fx"]["date"],
        "gemini_checked": pricing["checked_on"], "worst_type": usd(p["worst_type_usd"], 5),
    }
    v["oos_input"] = f"{p['stats']['by_type']['out_of_scope']['avg_input']:,.0f}"
    v["built"] = datetime.now(ZoneInfo("America/Sao_Paulo")).strftime("%d %B %Y").lstrip("0")
    cap = Settings().max_turns_per_day
    v["daily_cap"] = str(cap)
    v["abuse"] = f"{usd(cap * p['stats']['max_usd'])} ({brl(cap * p['stats']['max_usd'], rate)})"

    rows = []
    for t in cost_model.TYPE_ORDER:
        s, sa = p["stats"]["by_type"][t], a["stats"]["by_type"][t]
        rows.append(f"<tr><td>{TYPE_LABELS[t]}</td><td class=num>{s['avg_input']:,.0f}</td>"
                    f"<td class=num>{s['avg_output_and_thoughts']:,.0f}</td><td class=num>{usd(s['avg_usd'], 5)}</td>"
                    f"<td class=num>{usd(sa['avg_usd'], 5)}</td></tr>")
    v["type_rows"] = "\n".join(rows)
    rows = []
    for row, row_alt in zip(p["projection"], a["projection"]):
        cr = row["cloud_run"]["gross_usd"]
        total = row["gemini_usd"] + cr
        rows.append(f"<tr><td class=num>{row['conversations']:,}</td><td class=num>{usd(row['gemini_usd'])}</td>"
                    f"<td class=num>{usd(cr)}</td><td class=num><strong>{usd(total)}</strong></td>"
                    f"<td class=num><strong>{brl(total, rate)}</strong></td>"
                    f"<td class=num>{usd(row_alt['gemini_usd'] + row_alt['cloud_run']['gross_usd'])}</td></tr>")
        if row["conversations"] == 2000:
            v["month_2000"], v["month_2000_brl"] = usd(total), brl(total, rate)
            v["gemini_2000"] = usd(row["gemini_usd"])
            v["gemini_2000_8turns"] = usd(row["gemini_usd_8_turns_with_history"])
            v["gemini_2000_worst"] = usd(row["gemini_usd_worst_type"])
    v["monthly_rows"] = "\n".join(rows)

    qa = (ROOT / "docs" / "qa" / "README.md").read_text()
    v["tests"] = re.search(r"`(\d+) passed`", qa).group(1)
    v["mutations"] = re.search(r"`(\d+/\d+) mutations caught`", qa).group(1)
    v["browser_tests"] = re.search(r"\| `(\d+) passed` \|\n\| Browser, real model", qa).group(1)
    hosted = (ROOT / "docs" / "qa" / "hosted-results.md").read_text()
    verdicts = re.findall(r"\| (pass|FAIL) \| \[", hosted)
    v["hosted"] = f"{verdicts.count('pass')}/{len(verdicts)}"

    attacks = jsonl(f"{pinned}-s9sec")
    store = jsonl(f"{pinned}-s9") + jsonl(f"{alt}-s9")
    v["attack_turns"], v["attack_blockers"] = str(len(attacks)), str(sum(bool(r["blockers"]) for r in attacks))
    v["attack_kinds"] = str(len({r["scenario"] for r in attacks}))
    v["store_turns"], v["store_blockers"] = str(len(store)), str(sum(bool(r["blockers"]) for r in store))

    raws = [json.loads(Path(f).read_text()) for f in sorted(glob.glob(str(ROOT / "examples" / "raw" / "*.json")))]
    metas = {(r["meta"]["revision"], r["meta"]["commit"]) for r in raws}
    if len(metas) != 1:
        raise SystemExit(f"examples come from more than one revision: {metas}")
    v["revision"], v["commit"] = metas.pop()
    v["examples_pass"] = f"{sum(all(ok for _, ok in r['checks']) for r in raws)}/{len(raws)}"
    review = re.findall(r"^\| 0\d \|.*\| (PASS|NEEDS EDITS[^|]*|REWRITE[^|]*) \|$", (ROOT / "examples" / "README.md").read_text(), re.M)
    if len(review) != len(raws):
        raise SystemExit(f"examples/README.md reviews {len(review)} conversations, captured {len(raws)}")
    v["review_pass"] = str(sum(r == "PASS" for r in review))
    v["review_edits"] = str(sum(r.startswith("NEEDS EDITS") for r in review))
    return v


def render() -> Path:
    html = (DELIVERY / "report.template.html").read_text()
    for key, value in values().items():
        html = html.replace("{{" + key + "}}", value)
    left = sorted(set(re.findall(r"\{\{(\w+)\}\}", html)))
    if left:
        raise SystemExit(f"unresolved placeholders: {left}")
    out = DELIVERY / "report.html"
    out.write_text(html)
    return out


def main() -> int:
    from playwright.sync_api import sync_playwright

    html = render()
    pdf = ROOT / PDF_NAME
    with sync_playwright() as p:
        browser = p.chromium.launch()
        page = browser.new_page()
        page.goto(html.as_uri())
        page.wait_for_function("document.fonts.status === 'loaded'")
        page.pdf(path=str(pdf), format="A4", print_background=True, prefer_css_page_size=True)
        browser.close()
    print(f"wrote {html.relative_to(ROOT)} and {pdf.name} ({pdf.stat().st_size // 1024} KiB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
